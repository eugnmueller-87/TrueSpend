#!/usr/bin/env node
// =============================================================================
// sync-workflow-guards.js
//
// The deterministic guards live in workflows/lib/{reply_guard,invoice_guard}.js
// (the single source of truth, also imported by the Phase 1 tests). n8n Code
// nodes cannot require() local files, so each guarded workflow embeds a COPY of
// the guard as the Code node's jsCode. This script keeps the two in sync:
//
//   --check  (default): assert each workflow's embedded guard byte-matches the
//            freshly-generated bundle. Exit 1 on drift. Used in quality-gate.sh.
//   --write: regenerate the embedded jsCode in the workflow JSON from lib/.
//
// The "bundle" is the lib module's source with `module.exports`/`require`
// stripped and an n8n wrapper appended that reads $input/$node and returns the
// guard result. Generation is deterministic so --check is a pure equality test.
// =============================================================================

'use strict'
const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..')
const LIB = path.join(ROOT, 'workflows', 'lib')

// Strip the CommonJS scaffolding so the function bodies can be inlined.
function stripModule(src) {
  return src
    .replace(/^[ \t]*'use strict'[ \t]*\n/m, '')
    .replace(/^[ \t]*module\.exports[\s\S]*?\n/m, '')
    .trim()
}

const MARKER_BEGIN = '// <<<GUARD-BUNDLE:'
const MARKER_END   = '// >>>GUARD-BUNDLE-END'

function bundle(libFile, callExpr) {
  const src = stripModule(fs.readFileSync(path.join(LIB, libFile), 'utf8'))
  return [
    `${MARKER_BEGIN}${libFile}>>> generated by scripts/sync-workflow-guards.js — DO NOT EDIT HERE; edit workflows/lib/${libFile}`,
    src,
    '',
    '// ── n8n wrapper ──',
    callExpr,
    MARKER_END,
  ].join('\n')
}

// The n8n wrapper for each guard: pull inputs off $node, run the guard, and
// return a single item carrying the guard result merged with the parsed fields.
const REPLY_WRAPPER = `
const parsed = $node['Parse Claude Response'].json;
const ex = $node['Extract Email Data'].json;
const supplier = $node['Match Supplier in PostgREST'].json;
const openTickets = ($node['Fetch Open Tickets for Supplier'].json) || [];
// Thread parent resolved by the "Resolve Thread Parent" node (may be empty).
let threadParent = null;
try {
  const tp = $node['Resolve Thread Parent'].json;
  threadParent = Array.isArray(tp) ? (tp[0] || null) : (tp && tp.id ? tp : null);
} catch (e) { threadParent = null; }
const decision = validateReplyDecision({
  modelOutput: parsed,
  inbound: { subject: ex.subject, body: ex.body, from_email: ex.from_email, message_id: ex.message_id },
  supplierOpenTickets: openTickets,
  threadParent,
});
return [{ json: { ...parsed, ...(decision.safeFields || {}), guard_ok: decision.ok, route_to_human: decision.routeToHuman || !decision.ok, guard_reason: decision.reason || null } }];
`.trim()

const INVOICE_WRAPPER = `
const parsed = $node['Parse Claude Invoice Extraction'].json;
const meta = $node['Extract Email Metadata'].json;
const openPOs = ($node['Fetch Open POs for Supplier'].json) || [];
const decision = validateInvoiceExtraction({
  modelOutput: parsed,
  inbound: { subject: meta.subject, body_text: meta.body_text, attachment_content: meta.attachment_content },
  supplierOpenPOs: openPOs,
});
return [{ json: { ...parsed, ...(decision.safeFields || {}), guard_ok: decision.ok, route_to_human: decision.routeToHuman || !decision.ok, guard_reason: decision.reason || null } }];
`.trim()

const TARGETS = [
  {
    workflow: 'communication/supplier_reply_handler.json',
    nodeName: 'Validate Reply Decision',
    jsCode: bundle('reply_guard.js', REPLY_WRAPPER),
  },
  {
    workflow: 'automatic/invoice_processor.json',
    nodeName: 'Validate Invoice Extraction',
    jsCode: bundle('invoice_guard.js', INVOICE_WRAPPER),
  },
]

function findNode(wf, name) {
  return (wf.nodes || []).find(n => n.name === name)
}

const mode = process.argv.includes('--write') ? 'write' : 'check'
let drift = 0, missing = 0

for (const t of TARGETS) {
  const wfPath = path.join(ROOT, 'workflows', t.workflow)
  const wf = JSON.parse(fs.readFileSync(wfPath, 'utf8'))
  const node = findNode(wf, t.nodeName)
  if (!node) {
    console.log(`  ⚠ ${t.workflow}: node "${t.nodeName}" not present yet (wire it in, then run --write)`)
    missing++
    continue
  }
  const current = node.parameters && node.parameters.jsCode
  if (mode === 'write') {
    node.parameters = node.parameters || {}
    node.parameters.jsCode = t.jsCode
    fs.writeFileSync(wfPath, JSON.stringify(wf, null, 2) + '\n')
    console.log(`  ✓ wrote guard into ${t.workflow} :: ${t.nodeName}`)
  } else {
    if (current !== t.jsCode) {
      console.log(`  ✗ DRIFT: ${t.workflow} :: ${t.nodeName} differs from workflows/lib. Run: node scripts/sync-workflow-guards.js --write`)
      drift++
    } else {
      console.log(`  ✓ in sync: ${t.workflow} :: ${t.nodeName}`)
    }
  }
}

if (mode === 'check' && (drift || missing)) {
  if (drift) process.exit(1)
  // Missing nodes are a warning during the wiring phase, not a hard fail yet.
}
