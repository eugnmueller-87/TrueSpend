-- ── 3. Verify ────────────────────────────────────────────────────────────────
select
  cc.code,
  cc.name,
  b.name as branch,
  bp.category,
  bp.period,
  bp.planned,
  bp.committed,
  bp.spent,
  bp.planned - bp.committed - bp.spent as available
from budget_positions bp
join cost_centers cc on cc.id = bp.cost_center_id
join branches b on b.id = bp.branch_id
order by b.name, cc.code, bp.category
limit 40;
